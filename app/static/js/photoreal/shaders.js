/* app/static/js/photoreal/shaders.js
 *
 * GLSL ES 1.00 (WebGL1) shader sources for the photoreal window pass.
 * One full-screen triangle over the house canvas. Output is PREMULTIPLIED RGBA:
 * only the window, its reveal shading, wall AO / drop shadow and the sill get
 * alpha > 0. Every other pixel is alpha 0, so the photo stays untouched.
 *
 * Texture units (all uploaded with UNPACK_PREMULTIPLY_ALPHA_WEBGL = true,
 * LINEAR filtering, CLAMP_TO_EDGE):
 *   0 uLayer   R frame / G sash+panel / B muntin
 *   1 uHeight  bevelled height field
 *   2 uMask    R glass / G panel / B inside outer shape
 *   3 uFar     interior far layer
 *   4 uMid     interior mid layer (alpha)
 *   5 uNear    interior near layer (alpha)
 */
(function (root) {
  'use strict';

  var VERT = [
    'attribute vec2 aPos;',
    'void main() { gl_Position = vec4(aPos, 0.0, 1.0); }'
  ].join('\n');

  var FRAG = [
    '#ifdef GL_FRAGMENT_PRECISION_HIGH',
    'precision highp float;',
    '#else',
    'precision mediump float;',
    '#endif',
    '',
    'uniform sampler2D uLayer;',
    'uniform sampler2D uHeight;',
    'uniform sampler2D uMask;',
    'uniform sampler2D uFar;',
    'uniform sampler2D uMid;',
    'uniform sampler2D uNear;',
    '',
    'uniform mat3  uH;            // house px -> window texture px',
    'uniform vec2  uSrc;          // window texture size (px)',
    'uniform float uCanvasH;      // house canvas height (px)',
    'uniform vec2  uTexel;        // 1 / layer canvas size',
    'uniform float uAspect;       // window width / height',
    'uniform float uBarW;         // frame bar, in window-height units',
    '',
    'uniform float uRelief;       // bevel normal strength',
    'uniform float uDepthScale;   // height field -> world depth',
    'uniform float uWallH;        // wall plane height in height-field units',
    'uniform float uAORad;',
    'uniform float uAOStrength;',
    'uniform float uRevealW;      // reveal width (window-height units)',
    'uniform float uHasSill;',
    'uniform float uSillSize;',
    '',
    'uniform vec3  uFrameCol;',
    'uniform vec3  uSashCol;',
    'uniform vec3  uView;         // view vector (yaw / pitch)',
    'uniform float uReflect;      // reflection strength slider 0..1',
    'uniform float uOpacity;',
    'uniform float uBright;',
    'uniform float uIntensity;    // life slider 0..1',
    'uniform float uLife;         // transition 0..1',
    'uniform float uGlare;        // sweep position, <0 = off',
    'uniform float uInteriorBright;',
    '',
    'uniform vec3  uLightDir;',
    'uniform vec3  uSunTint;',
    'uniform vec3  uShadowTint;',
    'uniform float uSunStrength;',
    'uniform float uOvercast;',
    'uniform vec3  uAmbient;',
    'uniform vec3  uSky;',
    'uniform vec3  uWall;',
    'uniform vec3  uEnv[6];',
    'uniform vec3  uGain;',
    'uniform float uGrain;',
    'uniform float uExposure;',
    'uniform vec2  uShadowDir;',
    'uniform float uShadowSoft;',
    'uniform float uShadowStrength;',
    'uniform float uShadowLen;',
    '',
    '// ---------------------------------------------------------------',
    'vec3 toLin(vec3 c) { return pow(max(c, vec3(0.0)), vec3(2.2)); }',
    'vec3 toSRGB(vec3 c) { return pow(max(c, vec3(0.0)), vec3(1.0 / 2.2)); }',
    'float lum3(vec3 c) { return dot(c, vec3(0.2126, 0.7152, 0.0722)); }',
    'vec4 over(vec4 t, vec4 b) { return t + b * (1.0 - t.a); }',
    '',
    'float hash21(vec2 p) {',
    '  p = fract(p * vec2(123.34, 456.21));',
    '  p += dot(p, p + 45.32);',
    '  return fract(p.x * p.y);',
    '}',
    'float vnoise(vec2 p) {',
    '  vec2 i = floor(p);',
    '  vec2 f = fract(p);',
    '  f = f * f * (3.0 - 2.0 * f);',
    '  float a = hash21(i);',
    '  float b = hash21(i + vec2(1.0, 0.0));',
    '  float c = hash21(i + vec2(0.0, 1.0));',
    '  float d = hash21(i + vec2(1.0, 1.0));',
    '  return mix(mix(a, b, f.x), mix(c, d, f.x), f.y);',
    '}',
    '',
    'float inRect(vec2 p) {',
    '  return (p.x >= 0.0 && p.x <= 1.0 && p.y >= 0.0 && p.y <= 1.0) ? 1.0 : 0.0;',
    '}',
    'float inShape(vec2 p) {',
    '  if (inRect(p) < 0.5) return 0.0;',
    '  return texture2D(uMask, p).b;',
    '}',
    '// height field; outside the window shape = wall plane (stands proud of the frame)',
    'float hAt(vec2 p) {',
    '  if (inRect(p) < 0.5) return uWallH;',
    '  float m = texture2D(uMask, p).b;',
    '  float h = texture2D(uHeight, p).r;',
    '  return mix(uWallH, h, smoothstep(0.2, 0.8, m));',
    '}',
    '',
    '// ---- ring search: proximity (1 = touching) to the window shape from outside',
    'float ringProx(vec2 c, float R, out vec2 dir) {',
    '  vec2 upw = vec2(1.0 / uAspect, 1.0);',
    '  float best = 0.0;',
    '  dir = vec2(0.0);',
    '  for (int k = 0; k < 8; k++) {',
    '    float a = 0.785398 * float(k);',
    '    vec2 d = vec2(cos(a), sin(a));',
    '    for (int j = 1; j <= 4; j++) {',
    '      float r = R * float(j) / 4.0;',
    '      if (inShape(c + d * r * upw) > 0.5) {',
    '        float p = 1.0 - (float(j) - 0.5) / 4.0;',
    '        if (p > best) { best = p; dir = d; }',
    '        break;',
    '      }',
    '    }',
    '  }',
    '  return best;',
    '}',
    '',
    '// ---- cavity ambient occlusion from the height field',
    'float cavityAO(vec2 uv, float h0) {',
    '  float occ = 0.0;',
    '  for (int k = 0; k < 8; k++) {',
    '    float a = 0.785398 * float(k);',
    '    vec2 d = vec2(cos(a) / uAspect, sin(a));',
    '    occ += clamp((hAt(uv + d * uAORad) - h0) * 2.5, 0.0, 1.0);',
    '    occ += clamp((hAt(uv + d * uAORad * 2.4) - h0) * 1.8, 0.0, 1.0) * 0.7;',
    '  }',
    '  return 1.0 - clamp(occ / 13.6, 0.0, 1.0) * uAOStrength;',
    '}',
    '',
    '// ---- height-field shadow march toward the light',
    'float castShadow(vec2 uv, float h0, vec3 L) {',
    '  float ll = length(L.xy);',
    '  if (ll < 0.02) return 0.0;',
    '  vec2 dir = L.xy / ll;',
    '  float tanE = L.z / ll;',
    '  float stepW = max(uBarW * 0.28, 0.004);',
    '  float occ = 0.0;',
    '  for (int i = 1; i <= 6; i++) {',
    '    float d = stepW * float(i);',
    '    vec2 s = uv + vec2(dir.x / uAspect, dir.y) * d;',
    '    float hs = hAt(s);',
    '    float rayH = h0 * uDepthScale + d * tanE;',
    '    occ = max(occ, clamp((hs * uDepthScale - rayH) / 0.012, 0.0, 1.0));',
    '  }',
    '  return occ;',
    '}',
    '',
    '// ---- reflection environment (sky -> ground bands)',
    'vec3 envColor(float t) {',
    '  float pos = clamp(t, 0.0, 1.0) * 5.0;',
    '  vec3 c = vec3(0.0);',
    '  for (int i = 0; i < 6; i++) {',
    '    float w = max(0.0, 1.0 - abs(pos - float(i)));',
    '    c += uEnv[i] * w;',
    '  }',
    '  return c;',
    '}',
    '',
    '// ---------------------------------------------------------------',
    '// Window body: frame / sash / muntins (lit relief) + glass (Fresnel, interior, glints)',
    'vec4 windowBody(vec2 uv, vec3 mk, vec3 L) {',
    '  vec3 lay = texture2D(uLayer, uv).rgb;',
    '  float h0 = hAt(uv);',
    '  float gm = smoothstep(0.35, 0.65, mk.r);',
    '  vec3 V = normalize(uView);',
    '',
    '  // ---------- surfaces ----------',
    '  float lsum = lay.r + lay.g + lay.b;',
    '  vec3 alb = (uFrameCol * lay.r + uSashCol * (lay.g + lay.b)) / max(lsum, 0.05);',
    '  alb *= 1.0 + (vnoise(uv * vec2(uAspect, 1.0) * 260.0) - 0.5) * 0.05;',
    '  vec3 albL = toLin(alb);',
    '',
    '  float hl = hAt(uv - vec2(uTexel.x, 0.0));',
    '  float hr = hAt(uv + vec2(uTexel.x, 0.0));',
    '  float hu = hAt(uv - vec2(0.0, uTexel.y));',
    '  float hd = hAt(uv + vec2(0.0, uTexel.y));',
    '  vec3 N = normalize(vec3(-(hr - hl) * uRelief, -(hd - hu) * uRelief, 1.0));',
    '',
    '  float sh = castShadow(uv, h0, L);',
    '  float ao = cavityAO(uv, h0);',
    '  float ndl = max(dot(N, L), 0.0);',
    '  float expo = 0.75 + 0.5 * uExposure;',
    '  vec3 sunC = toLin(uSunTint) * uSunStrength * 1.35;',
    '  vec3 amb = toLin(uAmbient) * 0.6 * mix(vec3(1.0), toLin(uShadowTint), 0.5);',
    '  vec3 diff = (sunC * ndl * (1.0 - sh * 0.85) + amb * ao) * expo;',
    '  vec3 Hh = normalize(L + V);',
    '  float spec = pow(max(dot(N, Hh), 0.0), 48.0) * 0.22 * uSunStrength * (1.0 - sh);',
    '  vec3 surf = albL * diff + spec * toLin(uSunTint);',
    '  // soft sky rim on the bevels',
    '  surf += toLin(uSky) * 0.05 * (1.0 - N.z) * ao;',
    '',
    '  // ---------- glass ----------',
    '  vec2 pc = uv - 0.5;',
    '  vec3 Ng = normalize(vec3(pc.x * 0.30 * (0.4 + uReflect), pc.y * 0.22 * (0.4 + uReflect), 1.0));',
    '  float cosT = clamp(dot(Ng, V), 0.0, 1.0);',
    '  float F0 = 0.045 + 0.11 * uReflect;',
    '  float F = F0 + (1.0 - F0) * pow(1.0 - cosT, 5.0);',
    '  F = clamp(F * (0.8 + 0.6 * uReflect), 0.0, 0.85);',
    '',
    '  float ripple = (vnoise(uv * vec2(uAspect, 1.0) * 9.0) - 0.5) * 0.015;',
    '  vec3 Rf = reflect(-V, Ng);',
    '  float et = clamp(uv.y * 0.8 + 0.1 + Rf.y * 0.5 + ripple, 0.0, 1.0);',
    '  vec3 refl = toLin(envColor(et)) * mix(vec3(1.0), toLin(uSunTint), 0.4);',
    '',
    '  // interior room with 3-layer parallax (cover-fit, no stretching)',
    '  vec2 k = (uAspect > 1.0) ? vec2(1.0, 1.0 / uAspect) : vec2(uAspect, 1.0);',
    '  vec2 base = 0.5 + pc * k;',
    '  vec4 fa = texture2D(uFar,  base + V.xy * 0.010);',
    '  vec4 mi = texture2D(uMid,  base + pc * 0.030 + V.xy * 0.030);',
    '  vec4 ne = texture2D(uNear, base + pc * 0.070 + V.xy * 0.060);',
    '  vec3 room = fa.rgb;',
    '  room = room * (1.0 - mi.a) + mi.rgb;',
    '  room = room * (1.0 - ne.a) + ne.rgb;',
    '  float emissive = smoothstep(0.65, 1.0, lum3(room));',
    '  vec3 roomL = toLin(room) * (1.0 + emissive * 1.2);',
    '  float kInt = mix(0.90, 0.35, clamp(uExposure * 1.1, 0.0, 1.0)) * uInteriorBright;',
    '  vec3 glassTint = vec3(0.86, 0.95, 0.93);',
    '  vec3 trans = roomL * kInt * glassTint * (1.0 - F);',
    '',
    '  // diagonal glints crossing the glass',
    '  float diag = uv.x * 0.8 + (1.0 - uv.y) * 0.6 + ripple;',
    '  float b1 = smoothstep(0.33, 0.355, diag) * (1.0 - smoothstep(0.43, 0.48, diag));',
    '  float b2 = smoothstep(0.67, 0.685, diag) * (1.0 - smoothstep(0.725, 0.765, diag));',
    '  float g2 = 0.0;',
    '  if (uGlare >= 0.0) {',
    '    float gp = diag / 1.4;',
    '    float gw = 0.045;',
    '    float gs = smoothstep(uGlare - gw, uGlare - gw * 0.15, gp) * (1.0 - smoothstep(uGlare + gw * 0.15, uGlare + gw, gp));',
    '    float gc = 1.0 - smoothstep(0.0, gw * 0.35, abs(gp - uGlare));',
    '    g2 = gs * 0.75 + gc * 0.55;',
    '  }',
    '  float glint = (b1 * 0.26 + b2 * 0.14) * uReflect * (0.4 + 0.6 * uSunStrength) + g2 * 0.60;',
    '  vec3 glintC = toLin(uSunTint) * glint;',
    '',
    '  float gsh = castShadow(uv, 0.26, L);',
    '  vec3 glassCol = trans * (1.0 - 0.20 * gsh) + refl * F * (1.0 - 0.35 * gsh) + glintC * (1.0 - 0.6 * gsh);',
    '  glassCol *= mix(0.92, 1.0, cavityAO(uv, 0.26));',
    '',
    '  vec3 col = mix(surf, glassCol, gm);',
    '  col = toSRGB(col) * uGain * uBright;',
    '  col += (hash21(gl_FragCoord.xy) - 0.5) * 2.0 * uGrain / 255.0 * uIntensity;',
    '  return vec4(clamp(col, 0.0, 1.0), 1.0);',
    '}',
    '',
    '// ---------------------------------------------------------------',
    '// Exposed wall thickness (reveal) + soft wall AO / drop shadow. Pure shading',
    '// overlays: the stone / brick texture of the photo stays visible underneath.',
    'vec4 wallFx(vec2 uv, vec3 L) {',
    '  vec2 upw = vec2(1.0 / uAspect, 1.0);',
    '  vec4 res = vec4(0.0);',
    '',
    '  vec2 d2;',
    '  vec2 c2 = uv - uShadowDir * uShadowLen * upw;',
    '  float p2 = ringProx(c2, uShadowSoft * 1.4, d2);',
    '  if (p2 > 0.0) {',
    '    float a2 = pow(p2, 1.7) * uShadowStrength * 0.55 * uIntensity;',
    '    res = vec4(vec3(0.02) * uShadowTint * a2, a2);',
    '  }',
    '',
    '  vec2 d1;',
    '  float p1 = ringProx(uv, uRevealW, d1);',
    '  if (p1 > 0.0) {',
    '    vec2 ld = L.xy / max(length(L.xy), 0.001);',
    '    float lit = clamp(dot(d1, ld) * 0.5 + 0.5, 0.0, 1.0);',
    '    float depthK = mix(0.52, 1.0, 1.0 - p1);',
    '    float b = mix(0.40, 1.0, lit * uSunStrength + (1.0 - uSunStrength) * 0.6) * depthK;',
    '    float fade = smoothstep(0.0, 0.22, p1);',
    '    float a = (1.0 - b) * uIntensity * fade;',
    '    vec4 dk = vec4(vec3(0.015) * uShadowTint * a, a);',
    '    float la = max(lit - 0.72, 0.0) / 0.28 * 0.07 * uSunStrength * uIntensity * fade;',
    '    vec4 lt = vec4(uSunTint * la, la);',
    '    res = over(over(lt, dk), res);',
    '  }',
    '  return res;',
    '}',
    '',
    '// ---------------------------------------------------------------',
    '// Exterior cill (sill) with top face, front face and a shadow on the wall below.',
    'vec4 sillFx(vec2 uv, vec3 L) {',
    '  if (uHasSill < 0.5) return vec4(0.0);',
    '  float th = uSillSize;',
    '  float ov = 0.035;',
    '  float topH = th * 0.32;',
    '  float y = uv.y - 1.0;',
    '  float xin = smoothstep(-ov - 0.002, -ov + 0.002, uv.x) * (1.0 - smoothstep(1.0 + ov - 0.002, 1.0 + ov + 0.002, uv.x));',
    '  vec4 res = vec4(0.0);',
    '',
    '  float below = y - th;',
    '  if (below > 0.0 && below < th * 2.6) {',
    '    float fall = 1.0 - smoothstep(0.0, th * 2.6, below);',
    '    float side = smoothstep(-ov - 0.03, -ov + 0.01, uv.x) * (1.0 - smoothstep(1.0 + ov - 0.01, 1.0 + ov + 0.03, uv.x));',
    '    float a = fall * fall * uShadowStrength * 0.9 * uIntensity * side;',
    '    res = vec4(vec3(0.02) * uShadowTint * a, a);',
    '  }',
    '',
    '  if (y >= 0.0 && y <= th && xin > 0.0) {',
    '    float topLit = clamp(-L.y, 0.0, 1.0) * 0.9 + 0.15;',
    '    float frontLit = clamp(L.z, 0.0, 1.0) * 0.75 + 0.1;',
    '    float kk;',
    '    if (y < topH) {',
    '      kk = 1.12 + 0.10 * topLit;',
    '    } else {',
    '      float t = (y - topH) / max(th - topH, 0.0001);',
    '      kk = mix(0.96, 0.72, t) * (0.80 + 0.25 * frontLit);',
    '      if (y < topH + 0.004) kk *= 0.80;',
    '    }',
    '    float edge = min(uv.x + ov, 1.0 + ov - uv.x);',
    '    kk *= 0.85 + 0.15 * smoothstep(0.0, 0.02, edge);',
    '    vec3 c = uWall * kk;',
    '    c *= 1.0 + (vnoise(uv * vec2(uAspect, 1.0) * 160.0) - 0.5) * 0.10;',
    '    c += toLin(uSunTint) * 0.05 * uSunStrength * (1.0 - smoothstep(0.0, 0.006, y));',
    '    c *= 1.0 - 0.22 * smoothstep(th - 0.008, th, y);',
    '    c = clamp(c, 0.0, 1.0);',
    '    res = over(vec4(c * xin, xin), res);',
    '  }',
    '  return res;',
    '}',
    '',
    '// ---------------------------------------------------------------',
    'void main() {',
    '  vec2 px = vec2(gl_FragCoord.x, uCanvasH - gl_FragCoord.y);',
    '  vec3 q = uH * vec3(px, 1.0);',
    '  if (abs(q.z) < 1e-6) discard;',
    '  vec2 uv = q.xy / q.z / uSrc;',
    '  float M = 0.45;',
    '  if (uv.x < -M || uv.x > 1.0 + M || uv.y < -M || uv.y > 1.0 + M) discard;',
    '',
    '  vec3 L = normalize(uLightDir);',
    '  vec3 mk = vec3(0.0);',
    '  float cov = 0.0;',
    '  if (inRect(uv) > 0.5) {',
    '    mk = texture2D(uMask, uv).rgb;',
    '    cov = smoothstep(0.12, 0.88, mk.b);',
    '  }',
    '',
    '  vec4 wf = vec4(0.0);',
    '  if (cov < 0.999) wf = wallFx(uv, L) * (1.0 - cov);',
    '  vec4 sl = sillFx(uv, L);',
    '  vec4 bd = vec4(0.0);',
    '  if (cov > 0.001) bd = windowBody(uv, mk, L) * (cov * uOpacity);',
    '',
    '  vec4 res = over(bd, over(sl, wf)) * uLife;',
    '  if (res.a < 0.003) discard;',
    '  gl_FragColor = res;',
    '}'
  ].join('\n');

  var UNIFORMS = [
    'uLayer', 'uHeight', 'uMask', 'uFar', 'uMid', 'uNear',
    'uH', 'uSrc', 'uCanvasH', 'uTexel', 'uAspect', 'uBarW',
    'uRelief', 'uDepthScale', 'uWallH', 'uAORad', 'uAOStrength', 'uRevealW',
    'uHasSill', 'uSillSize',
    'uFrameCol', 'uSashCol', 'uView', 'uReflect', 'uOpacity', 'uBright',
    'uIntensity', 'uLife', 'uGlare', 'uInteriorBright',
    'uLightDir', 'uSunTint', 'uShadowTint', 'uSunStrength', 'uOvercast',
    'uAmbient', 'uSky', 'uWall', 'uEnv', 'uGain', 'uGrain', 'uExposure',
    'uShadowDir', 'uShadowSoft', 'uShadowStrength', 'uShadowLen'
  ];

  var DEFAULTS = {
    relief: 11.0,
    depthScale: 0.05,
    wallH: 1.6,
    aoRad: 0.012,
    aoStrength: 0.85,
    revealW: 0.04,
    sillSize: 0.055,
    interiorBright: 0.85
  };

  var api = { VERT: VERT, FRAG: FRAG, UNIFORMS: UNIFORMS, DEFAULTS: DEFAULTS };
  root.PhotorealShaders = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : this);
